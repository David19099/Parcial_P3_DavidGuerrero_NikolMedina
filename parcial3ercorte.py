import os

# Nombre del archivo plano para la persistencia de datos (Capa de Datos)
NOMBRE_ARCHIVO = "inspecciones_ifn.txt"


# ==============================================================================
# 1. CAPA DE DATOS (Persistencia y Lectura/Escritura en Archivos Planos)
# ==============================================================================

def guardar_registro_txt(registro_linea):
    """
    Recibe una cadena formateada con los datos de la inspección y la concatena
    al final del archivo de texto plano. Retorna True si fue exitoso.
    """
    try:
        with open(NOMBRE_ARCHIVO, "a", encoding="utf-8") as archivo:
            archivo.write(registro_linea + "\n")
        return True
    except IOError as error:
        print(f"Error físico al intentar escribir en el archivo plano: {error}")
        return False


def leer_registros_txt():
    """
    Abre el archivo plano en modo lectura y retorna una lista con cada una
    de las líneas almacenadas. Si el archivo no existe, retorna una lista vacía.
    """
    if not os.path.exists(NOMBRE_ARCHIVO):
        return []

    try:
        with open(NOMBRE_ARCHIVO, "r", encoding="utf-8") as archivo:
            lineas = archivo.readlines()
        return lineas
    except IOError as error:
        print(f"Error físico al intentar leer el archivo plano: {error}")
        return []


# ==============================================================================
# 2. CAPA DE LÓGICA DE NEGOCIO (Procesamiento, Validación y Filtrado)
# ==============================================================================

def procesar_nueva_inspeccion(idConglomerado, geolocalizacion, nombreBrigada,
                               fustales, latizales, brinzales,
                               nombreComunEspecie, usoEspecie, codigoMuestra):
    """
    Formatea las variables de entrada utilizando un delimitador '|'
    y las envía a la Capa de Datos para su almacenamiento.
    """
    # Construcción de la trama de texto delimitada
    registro_linea = (
        f"{idConglomerado}|{geolocalizacion}|{nombreBrigada}|"
        f"{fustales}|{latizales}|{brinzales}|"
        f"{nombreComunEspecie}|{usoEspecie}|{codigoMuestra}"
    )

    # Invocación de la persistencia
    exito = guardar_registro_txt(registro_linea)
    return exito


def buscar_inspeccion_logica(idBuscado):
    """
    Obtiene los registros del archivo plano desde la Capa de Datos, los analiza
    línea por línea y retorna un diccionario con las variables del conglomerado encontrado.
    """
    lineas = leer_registros_txt()

    for linea in lineas:
        linea_limpia = linea.strip()
        if linea_limpia:
            campos = linea_limpia.split("|")

            # Verificación del formato del registro (debe tener exactamente 9 campos)
            if len(campos) == 9:
                id_actual = campos[0]
                if id_actual == idBuscado:
                    # Se empaquetan las variables en una estructura de datos
                    inspeccion_encontrada = {
                        "idConglomerado": campos[0],
                        "geolocalizacion": campos[1],
                        "nombreBrigada": campos[2],
                        "fustales": int(campos[3]),
                        "latizales": int(campos[4]),
                        "brinzales": int(campos[5]),
                        "nombreComunEspecie": campos[6],
                        "usoEspecie": campos[7],
                        "codigoMuestra": campos[8]
                    }
                    return inspeccion_encontrada
    return None


def obtener_todas_las_inspecciones_logica():
    """
    Parsea todos los registros almacenados en el archivo plano para
    generar informes agregados e indicadores a nivel general.
    """
    lineas = leer_registros_txt()
    lista_inspecciones = []

    for linea in lineas:
        linea_limpia = linea.strip()
        if linea_limpia:
            campos = linea_limpia.split("|")
            if len(campos) == 9:
                inspeccion = {
                    "idConglomerado": campos[0],
                    "geolocalizacion": campos[1],
                    "nombreBrigada": campos[2],
                    "fustales": int(campos[3]),
                    "latizales": int(campos[4]),
                    "brinzales": int(campos[5]),
                    "nombreComunEspecie": campos[6],
                    "usoEspecie": campos[7],
                    "codigoMuestra": campos[8]
                }
                lista_inspecciones.append(inspeccion)

    return lista_inspecciones


