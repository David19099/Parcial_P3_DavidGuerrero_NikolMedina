# 3. CAPA DE PRESENTACIÓN (Interfaz de Usuario en Consola)
# ==============================================================================

def capturar_datos_inspeccion():
    """
    Solicita al usuario los datos de entrada requeridos mediante la consola,
    utilizando los nombres de variables exactos especificados.
    """
    print("\n---------------------------------------------------------")
    print("      REGISTRO DE NUEVA INSPECCIÓN FORESTAL (IFN)")
    print("---------------------------------------------------------")

    # 1. Datos del conglomerado y ubicación
    idConglomerado = input("Ingrese el ID del Conglomerado: ").strip()
    geolocalizacion = input("Ingrese la geolocalización / ubicación subparcelas: ").strip()

    # 2. Datos de la brigada
    nombreBrigada = input("Ingrese el nombre de la Brigada asignada: ").strip()

    # 3. Conteo de árboles
    while True:
        try:
            fustales = int(input("Ingrese la cantidad de árboles FUSTALES: "))
            latizales = int(input("Ingrese la cantidad de árboles LATIZALES: "))
            brinzales = int(input("Ingrese la cantidad de árboles BRINZALES: "))
            if fustales >= 0 and latizales >= 0 and brinzales >= 0:
                break
            else:
                print("¡Error! Las cantidades de árboles deben ser mayores o iguales a cero.")
        except ValueError:
            print("¡Error! Debe ingresar un valor numérico entero.")

    # 4. Datos de muestreo
    nombreComunEspecie = input("Ingrese el nombre común de la especie: ").strip()
    usoEspecie = input("Ingrese el uso de la especie (medicinal / alimenticio / maderable): ").strip()
    codigoMuestra = input("Ingrese el código de identificación de la muestra: ").strip()

    # Enviar a la capa de lógica para su procesamiento
    resultado = procesar_nueva_inspeccion(
        idConglomerado, geolocalizacion, nombreBrigada,
        fustales, latizales, brinzales,
        nombreComunEspecie, usoEspecie, codigoMuestra
    )

    if resultado:
        print("\n--> ¡ÉXITO! Inspección registrada y persistida en el archivo plano.")
    else:
        print("\n--> ¡ERROR! No se pudo guardar la inspección en el archivo.")


def consultar_inspeccion_por_id():
    """
    Solicita el ID del conglomerado y muestra los datos exactos de salida en pantalla.
    """
    print("\n---------------------------------------------------------")
    print("        CONSULTA DE INSPECCIÓN POR CONGLOMERADO")
    print("---------------------------------------------------------")
    idBuscado = input("Ingrese el ID del Conglomerado a consultar: ").strip()

    inspeccion = buscar_inspeccion_logica(idBuscado)

    if inspeccion:
        print("\n---------------------------------------------------------")
        print("          DATOS DE LA INSPECCIÓN ENCONTRADA")
        print("---------------------------------------------------------")
        print(f"ID Conglomerado        : {inspeccion['idConglomerado']}")
        print(f"Geolocalización        : {inspeccion['geolocalizacion']}")
        print(f"Brigada Asignada       : {inspeccion['nombreBrigada']}")
        print(f"Conteo Fustales        : {inspeccion['fustales']}")
        print(f"Conteo Latizales       : {inspeccion['latizales']}")
        print(f"Conteo Brinzales       : {inspeccion['brinzales']}")
        print(f"Nombre Común Especie   : {inspeccion['nombreComunEspecie']}")
        print(f"Uso de la Especie      : {inspeccion['usoEspecie']}")
        print(f"Código de Muestra      : {inspeccion['codigoMuestra']}")
        print("---------------------------------------------------------")
    else:
        print(f"\n--> ¡INFORMACIÓN! No se encontró ninguna inspección asociada al ID: '{idBuscado}'.")


def generar_informes_indicadores():
    """
    Muestra los datos de salida consolidados, incluyendo listado de especies,
    usos, distribución geográfica e indicadores (densidad de cobertura vegetal).
    """
    inspecciones = obtener_todas_las_inspecciones_logica()

    if not inspecciones:
        print("\n--> No existen inspecciones registradas en el archivo plano para calcular indicadores.")
        return

    print("\n=========================================================")
    print("    INFORMES REGIONALES E INDICADORES FORESTALES (IFN)")
    print("=========================================================")

    total_inspecciones = len(inspecciones)
    total_arboles = 0
    especies_presentes = set()
    usos_presentes = set()

    for i in inspecciones:
        suma_conglomerado = i["fustales"] + i["latizales"] + i["brinzales"]
        total_arboles += suma_conglomerado
        especies_presentes.add(i["nombreComunEspecie"])
        usos_presentes.add(i["usoEspecie"])

    # Cálculo del indicador: Densidad Promedio de Cobertura Vegetal por conglomerado
    densidad_cobertura_vegetal = total_arboles / total_inspecciones if total_inspecciones > 0 else 0

    print(f"Total de Conglomerados Evaluados : {total_inspecciones}")
    print(f"Total de Árboles Contados       : {total_arboles}")
    print(f"Densidad de Cobertura Vegetal    : {densidad_cobertura_vegetal:.2f} árboles/conglomerado")
    print(f"Especies Presentes              : {', '.join(especies_presentes)}")
    print(f"Usos Registrados                : {', '.join(usos_presentes)}")
    print("=========================================================")


